-- ====================================================================
-- E-Commerce Storefront - Supabase Database Schema & Security Policies
-- ====================================================================

-- 1. Create the Products Table
CREATE TABLE IF NOT EXISTS public.products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL CHECK (char_length(trim(name)) > 0),
    cat TEXT NOT NULL CHECK (char_length(trim(cat)) > 0),
    price NUMERIC(10, 2) NOT NULL CHECK (price >= 0),
    old NUMERIC(10, 2) CHECK (old IS NULL OR old >= 0),
    rating NUMERIC(3, 2) NOT NULL DEFAULT 0.0 CHECK (rating >= 0 AND rating <= 5),
    reviews INTEGER NOT NULL DEFAULT 0 CHECK (reviews >= 0),
    tags TEXT[] NOT NULL DEFAULT '{}'::TEXT[],
    "desc" TEXT NOT NULL DEFAULT '',
    info TEXT[] NOT NULL DEFAULT '{}'::TEXT[],
    image TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- Performance Indexes
CREATE INDEX IF NOT EXISTS idx_products_cat ON public.products(cat);
CREATE INDEX IF NOT EXISTS idx_products_is_active ON public.products(is_active);
CREATE INDEX IF NOT EXISTS idx_products_created_at ON public.products(created_at DESC);

-- Automatic Updated-At Trigger
CREATE OR REPLACE FUNCTION public.handle_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = timezone('utc'::text, now());
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS set_products_updated_at ON public.products;
CREATE TRIGGER set_products_updated_at
    BEFORE UPDATE ON public.products
    FOR EACH ROW
    EXECUTE FUNCTION public.handle_updated_at();

-- 2. Row Level Security (RLS) Configuration
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;

-- Policy 1: Public SELECT (Allow anyone to view active products, authenticated admins see all)
DROP POLICY IF EXISTS "Public can view active products" ON public.products;
CREATE POLICY "Public can view active products"
    ON public.products
    FOR SELECT
    TO public
    USING (is_active = true OR auth.role() = 'authenticated');

-- Policy 2: Authenticated INSERT (Only authenticated admins can add products)
DROP POLICY IF EXISTS "Authenticated users can insert products" ON public.products;
CREATE POLICY "Authenticated users can insert products"
    ON public.products
    FOR INSERT
    TO authenticated
    WITH CHECK (true);

-- Policy 3: Authenticated UPDATE (Only authenticated admins can update products)
DROP POLICY IF EXISTS "Authenticated users can update products" ON public.products;
CREATE POLICY "Authenticated users can update products"
    ON public.products
    FOR UPDATE
    TO authenticated
    USING (true)
    WITH CHECK (true);

-- Policy 4: Authenticated DELETE (Only authenticated admins can delete products)
DROP POLICY IF EXISTS "Authenticated users can delete products" ON public.products;
CREATE POLICY "Authenticated users can delete products"
    ON public.products
    FOR DELETE
    TO authenticated
    USING (true);

-- 3. Enable Realtime Replication
-- Allows frontend clients subscribed via supabase.channel() to receive realtime events
ALTER PUBLICATION supabase_realtime ADD TABLE public.products;
ALTER TABLE public.products REPLICA IDENTITY FULL;

